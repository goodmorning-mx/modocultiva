export function globalIdeaTitle(language: AppLanguage, mode: GlobalIdeaMode, level: number, variant: number): string {
  const practice = globalIdeaPractices[language][mode][level];
  const prompts = variantPrompts[language];
  const prompt = prompts[variant % (prompts.length + 1) - 1];
  // The Spanish originals fit an infinitive clause after the colon. Other
  // languages keep the instruction intact as a sentence with an optional next step.
  if (!prompt) return practice;
  return language === 'es' ? `${prompt}: ${practice.toLocaleLowerCase('es')}` : `${practice} ${prompt}`;
}
